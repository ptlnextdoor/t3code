/**
 * JcodeAdapterLive — jcode CLI (`jcode acp`) via ACP.
 *
 * Adapted from {@link ./CursorAdapter}. jcode speaks plain ACP: no Cursor
 * `ask_question` / `create_plan` / `update_todos` extension methods, and (for
 * now) no mode/model-picker parity — model selection is deferred per the
 * provider plan. What remains is the generic ACP core: session lifecycle,
 * permission requests, plan/tool-call/content streaming, and image-capable
 * prompts.
 *
 * @module JcodeAdapterLive
 */

